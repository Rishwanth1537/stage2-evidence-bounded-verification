"""
External Evaluator — Grounded Fact Verification Benchmark

Evaluates the entailment component of the pipeline against a curated set of
grounded fact-checking pairs derived from the LLM-AggreFact / MiniCheck
benchmark distribution (Liyan et al., 2024).

The default source is a small locally authored smoke test. For a publishable
evaluation, use ``--source hf`` to load the public LLM-AggreFact test split.
Its premise is a source document and its hypothesis is a claim generated by an
LLM. Labels follow the benchmark convention: True = supported by the document,
False = not supported (hallucinated or contradicted).

The cases deliberately exercise the failure modes that reasoning models exhibit:
- Numeric mutations
- Temporal/date hallucinations
- Entity substitutions
- Partial omission (true in isolation but missing key qualifiers)
- Contradiction (claim says X when document says not-X)

Usage:
    python benchmarks/external_eval.py
    python benchmarks/external_eval.py --verbose
    python benchmarks/external_eval.py --output benchmarks/external_results.json
    python benchmarks/external_eval.py --source hf --split test \
        --output benchmarks/aggrefact_results.json --verbose

This script evaluates only the entailment component (DeBERTa NLI), NOT the
full GED pipeline, so results reflect DeBERTa's pure claim-verification
performance in isolation. This maps directly to MiniCheck's evaluation
methodology using cross-encoder NLI.
"""
