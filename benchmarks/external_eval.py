def _metrics(tp: int, fp: int, tn: int, fn: int) -> Dict:
    total = tp + fp + tn + fn
    accuracy = (tp + tn) / total if total else 0.0
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0
    ba = 0.5 * (tp / (tp + fn) if (tp + fn) else 0.0) + \
         0.5 * (tn / (tn + fp) if (tn + fp) else 0.0)
    return {
        "accuracy": round(accuracy, 4),
        "balanced_accuracy": round(ba, 4),
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1": round(f1, 4),
        "tp": tp, "fp": fp, "tn": tn, "fn": fn,
        "total": total,
    }


def load_public_pairs(
    dataset_id: str = PUBLIC_DATASET_ID,
    split: str = "test",
    limit: int | None = None,
    seed: int = 42,
) -> Tuple[List[Dict], Dict]:
    """Load a documented grounded-fact benchmark from Hugging Face Datasets."""
    try:
        from datasets import load_dataset
    except ImportError as exc:
        raise RuntimeError(
            "Public evaluation requires the benchmark extra: "
            "pip install -e '.[benchmark]'"
        ) from exc

    dataset = load_dataset(dataset_id, split=split)
    required_columns = {"doc", "claim", "label"}
    missing = required_columns - set(dataset.column_names)
    if missing:
        raise ValueError(
            f"Dataset {dataset_id!r} is missing required columns: {sorted(missing)}"
        )

    if limit is not None:
        if limit < 1:
            raise ValueError("--limit must be at least 1")
        dataset = dataset.shuffle(seed=seed).select(range(min(limit, len(dataset))))

    pairs = [
        {
            "id": f"{dataset_id}:{split}:{index}",
            "label": bool(row["label"]),
            "premise": row["doc"],
            "hypothesis": row["claim"],
            "source_dataset": row.get("dataset"),
            "contamination_identifier": row.get("contamination_identifier"),
        }
        for index, row in enumerate(dataset)
    ]
    metadata = {
        "source": "huggingface",
        "dataset_id": dataset_id,
        "split": split,
        "seed": seed if limit is not None else None,
        "limit": limit,
        "rows_loaded": len(pairs),
        "license": "cc-by-nd-4.0",
        "dataset_url": f"https://huggingface.co/datasets/{dataset_id}",
    }
    return pairs, metadata


def load_local_pairs(
    local_dir: str | Path,
    split: str = "test",
    limit: int | None = None,
    seed: int = 42,
) -> Tuple[List[Dict], Dict]:
    """Load a downloaded LLM-AggreFact parquet shard from disk."""
    try:
        from datasets import load_dataset
    except ImportError as exc:
        raise RuntimeError(
            "Local parquet evaluation requires the benchmark extra: "
            "pip install -e '.[benchmark]'"
        ) from exc

    root = Path(local_dir)
    shards = sorted(root.glob(f"{split}-*.parquet"))
    if not shards:
        raise FileNotFoundError(
            f"No {split}-*.parquet shard found in {root.resolve()}"
        )

    dataset = load_dataset(
        "parquet",
        data_files=[str(path) for path in shards],
        split="train",
    )
    required_columns = {"doc", "claim", "label"}
    missing = required_columns - set(dataset.column_names)
    if missing:
        raise ValueError(
            f"Local dataset is missing required columns: {sorted(missing)}"
        )

    if limit is not None:
        if limit < 1:
            raise ValueError("--limit must be at least 1")
        dataset = dataset.shuffle(seed=seed).select(range(min(limit, len(dataset))))

    pairs = [
        {
            "id": f"local:{split}:{index}",
            "label": bool(row["label"]),
            "premise": row["doc"],
            "hypothesis": row["claim"],
            "source_dataset": row.get("dataset"),
            "contamination_identifier": row.get("contamination_identifier"),
        }
        for index, row in enumerate(dataset)
    ]
    metadata = {
        "source": "local_parquet",
        "dataset_id": PUBLIC_DATASET_ID,
        "split": split,
        "local_dir": str(root.resolve()),
        "shards": [str(path.resolve()) for path in shards],
        "seed": seed if limit is not None else None,
        "limit": limit,
        "rows_loaded": len(pairs),
        "license": "cc-by-nd-4.0",
        "dataset_url": f"https://huggingface.co/datasets/{PUBLIC_DATASET_ID}",
    }
    return pairs, metadata


def evaluate_entailment(
    pairs: List[Dict],
    entailment_threshold: float = 0.40,
    verbose: bool = False,
) -> Tuple[Dict, List[Dict]]:
    """
    Evaluate entailment-only component on the given pairs.

    Uses the same DeBERTa NLI model and batched inference as the production
    pipeline, but skips GED entirely. This isolates the NLI component's
    standalone performance.

    A claim is predicted as "supported" (True) if the entailment score ≥ threshold.
    """
    from server.pipeline.entailment import score_spans

    # Use _make_hypothesis on the full hypothesis to get the NLI template,
    # then score it against the premise.
    scored = []
    for rec in pairs:
        scores = score_spans(rec["premise"], [rec["hypothesis"]])
        entail_score = scores[0][1] if scores else 0.0
        scored.append((rec, entail_score))

    tp = fp = tn = fn = 0
    predictions = []
    for rec, score in scored:
        pred = score >= entailment_threshold
        true = rec["label"]

        if pred and true:
            tp += 1
            outcome = "TP  "
        elif pred and not true:
            fp += 1
            outcome = "FP! "
        elif not pred and not true:
            tn += 1
            outcome = "TN  "
        else:
            fn += 1
            outcome = "FN! "

        if verbose:
            print(
                f"  [{rec['id']:>4}] {outcome:<5}  pred={str(pred):<5}  "
                f"truth={str(true):<5}  entail={score:.4f}"
            )

        predictions.append({
            "id": rec["id"],
            "prediction": pred,
            "ground_truth": true,
            "entailment_score": round(score, 4),
            "hypothesis": rec["hypothesis"],
            "premise": rec["premise"][:80] + "…" if len(rec["premise"]) > 80 else rec["premise"],
        })

    metrics = _metrics(tp, fp, tn, fn)
    return metrics, predictions


def main() -> None:
    parser = argparse.ArgumentParser(description="External grounded fact-checking evaluation")
    parser.add_argument(
        "--source", choices=("curated", "hf", "local"), default="curated",
        help="Evaluation source: curated smoke test, Hugging Face, or local parquet.",
    )
    parser.add_argument("--dataset-id", default=PUBLIC_DATASET_ID)
    parser.add_argument(
        "--local-dir", default=".",
        help="Directory containing <split>-*.parquet files when --source=local.",
    )
    parser.add_argument("--split", default="test", choices=("dev", "test"))
    parser.add_argument(
        "--limit", type=int, default=None,
        help="Optional deterministic sample size for the public dataset.",
    )
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--threshold", default=0.40, type=float, help="Entailment score threshold")
    parser.add_argument("--output", default=None, type=str, help="Optional JSON output path")
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    if args.source == "hf":
        pairs, source_metadata = load_public_pairs(
            dataset_id=args.dataset_id,
            split=args.split,
            limit=args.limit,
            seed=args.seed,
        )
    elif args.source == "local":
        pairs, source_metadata = load_local_pairs(
            local_dir=args.local_dir,
            split=args.split,
            limit=args.limit,
            seed=args.seed,
        )
    else:
        pairs = EXTERNAL_PAIRS
        source_metadata = {
            "source": "curated",
            "rows_loaded": len(pairs),
            "note": "Locally authored smoke-test cases; not an independent benchmark.",
        }

    if args.verbose:
        print(f"Evaluating {len(pairs)} grounded fact-checking pairs "
              f"(entailment-only, threshold={args.threshold})…\n")

    metrics, predictions = evaluate_entailment(
        pairs,
        entailment_threshold=args.threshold,
        verbose=args.verbose,
    )

    print(f"\n{'='*55}")
    print(f"External Grounded Fact-Checking Evaluation (n={metrics['total']})")
    print(f"{'='*55}")
    print(f"  Accuracy          : {metrics['accuracy']:.4f}")
    print(f"  Balanced Accuracy : {metrics['balanced_accuracy']:.4f}  ← primary metric")
    print(f"  Precision         : {metrics['precision']:.4f}")
    print(f"  Recall            : {metrics['recall']:.4f}")
    print(f"  F1                : {metrics['f1']:.4f}")
    print(f"  TP={metrics['tp']}  FP={metrics['fp']}  TN={metrics['tn']}  FN={metrics['fn']}")
    print(f"{'='*55}")
    print("\nNote: MiniCheck DeBERTa-large achieves ~75.8% balanced accuracy on")
    print("LLM-AggreFact. Scores above 70% indicate competitive performance.")

    if args.output:
        out = Path(args.output)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps({
            "source": source_metadata,
            "threshold": args.threshold,
            "metrics": metrics,
            "predictions": predictions,
        }, indent=2))
        print(f"\nResults written to {args.output}")


if __name__ == "__main__":
    main()
